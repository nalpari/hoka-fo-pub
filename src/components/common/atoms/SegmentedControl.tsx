'use client';

import { Toggle } from '@base-ui/react/toggle';
import { ToggleGroup } from '@base-ui/react/toggle-group';
import type { ReactElement, ReactNode } from 'react';

import { cva } from 'styled-system/css';

import { Button } from '@/components/common/atoms/Button';
import { Typography } from '@/components/common/atoms/Typography';

const root = cva({
  base: { display: 'flex', flexWrap: 'wrap', gap: '2' },
  variants: {
    fullWidth: { true: { '& > button': { flex: '1' } }, false: {} },
    variant: {
      default: {},
      underline: {
        w: '100%',
        flexWrap: 'nowrap',
        gap: '0',
        borderBottom: '1px solid var(--colors-black-20)',
      },
    },
  },
  defaultVariants: { fullWidth: false, variant: 'default' },
});

const item = cva({
  base: { borderColor: 'var(--color-black-20)' },
  variants: {
    variant: {
      default: {},
      underline: {
        flex: '1',
        minW: '0',
        minH: '32px',
        border: '0',
        borderBottom: '2px solid transparent',
        bg: 'transparent',
        color: 'var(--color-text-primary)',
        cursor: 'pointer',
      },
    },
    active: {
      true: {
        borderColor: 'var(--color-black-100)',
        bg: 'var(--color-black-100)',
        color: 'var(--color-text-inverse)',
      },
      false: {},
    },
  },
  compoundVariants: [
    {
      variant: 'underline',
      active: true,
      css: {
        bg: 'transparent',
        color: 'var(--color-text-primary)',
        borderBottomColor: 'var(--color-black-100)',
      },
    },
  ],
});

export type SegmentedControlOption<T extends string = string> = {
  value: T;
  label: ReactNode;
  disabled?: boolean;
};

export type SegmentedControlProps<T extends string = string> = {
  options: readonly SegmentedControlOption<T>[];
  value: T;
  onValueChange: (value: T) => void;
  ariaLabel: string;
  fullWidth?: boolean;
  variant?: 'default' | 'underline';
  className?: string;
  /** Use native toggle buttons and let the caller own all presentation styles. */
  unstyled?: boolean;
  itemClassName?: (option: SegmentedControlOption<T>, selected: boolean) => string | undefined;
  /** Custom button renderer; Base UI preserves selection, focus and keyboard behavior. */
  itemRender?: (option: SegmentedControlOption<T>) => ReactElement;
};

/** 탭 패널을 전환하지 않는 단일 선택 필터와 보기 모드를 표시합니다. (Displays accessible single-choice filters and view modes without controlling tab panels.) */
export function SegmentedControl<T extends string = string>({
  options,
  value,
  onValueChange,
  ariaLabel,
  fullWidth,
  variant = 'default',
  className,
  unstyled = false,
  itemClassName,
  itemRender,
}: SegmentedControlProps<T>) {
  return (
    <ToggleGroup
      aria-label={ariaLabel}
      className={[unstyled ? '' : root({ fullWidth, variant }), className]
        .filter(Boolean)
        .join(' ')}
      onValueChange={(nextValue) => {
        const next = nextValue[0];
        const option = options.find(
          (option) => JSON.stringify(option.value) === next && !option.disabled,
        );
        if (option) onValueChange(option.value);
      }}
      // Base UI 1.8 treats an empty toggle value as an autogenerated ID.
      // Encode every string to keep the public value contract collision-free.
      value={[JSON.stringify(value)]}
    >
      {options.map((option) => (
        <Toggle
          disabled={option.disabled}
          key={option.value}
          className={[
            !unstyled && variant === 'underline'
              ? item({ variant, active: option.value === value })
              : '',
            itemClassName?.(option, option.value === value),
          ]
            .filter(Boolean)
            .join(' ')}
          render={
            itemRender?.(option) ??
            (unstyled ? undefined : variant === 'underline' ? (
              <Typography as="button" variant="body3" weight="medium" tone="primary">
                {option.label}
              </Typography>
            ) : (
              <Button className={item({ variant, active: option.value === value })} />
            ))
          }
          value={JSON.stringify(option.value)}
        >
          {option.label}
        </Toggle>
      ))}
    </ToggleGroup>
  );
}
