function normalizeScreens(rawDefinitions: readonly RawScreenDefinition[]): ScreenDefinition[] {
  const inheritedDepths = ['', '', '', '', ''];

  return rawDefinitions.map(
    ([iaNumber, rawDepths, category, page, requiresLogin, screenCode, note]) => {
      rawDepths.forEach((depth, index) => {
        if (!depth) return;

        inheritedDepths[index] = depth;

        for (
          let descendantIndex = index + 1;
          descendantIndex < inheritedDepths.length;
          descendantIndex += 1
        ) {
          inheritedDepths[descendantIndex] = '';
        }
      });

      return {
        iaNumber,
        depths: [...inheritedDepths] as ScreenDefinition['depths'],
        category,
        page,
        requiresLogin,
        screenCode,
        note,
      };
    },
  );
}

export const screens = normalizeScreens(rawScreens);
